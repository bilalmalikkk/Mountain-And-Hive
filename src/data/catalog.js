export function getProduct(id) {
  return products.find((product) => product.id === id)
}

export function getCategory(id) {
  return categories.find((category) => category.id === id)
}

export function relatedProducts(product, count = 4) {
  const same = products.filter((item) => item.category === product.category && item.id !== product.id)
  const more = products.filter((item) => item.featured && item.id !== product.id && !same.includes(item))
  return [...same, ...more].slice(0, count)
}

